  assert.match(css, /\.craft-assist-editor-card\s*\{[^}]*grid-template-rows:/s);
  assert.match(css, /\.craft-assist-editor-columns\s*\{[^}]*grid-template-columns:/s);
  assert.match(css, /\.craft-assist-editor-column\s*\{[^}]*overflow:\s*hidden/s);
  assert.match(css, /body\.theme-inkblue \.craft-assist-editor-modal \.craft-assist-item[\s\S]*background:\s*rgba\(12, 17, 25, 0\.9\)/s);
  assert.match(css, /\.craft-assist-preset-list\s*\{[^}]*grid-template-columns:\s*repeat\(auto-fill,/s);
  assert.match(css, /\.craft-assist-editor-left\s+\.craft-assist-material-card-list\s*\{[^}]*grid-template-columns:\s*repeat\(4,/s);
  const editorWidth = css.match(/\.craft-assist-editor-card\s*\{[^}]*width:\s*min\((\d+)px,/s);
  assert.ok(editorWidth && Number(editorWidth[1]) > 1320, "craft assist editor should be wider than 1320px");
  assert.match(css, /\.craft-assist-outcome-modal-card\s*\{/);
  assert.match(css, /\.craft-assist-editor-role-btn\.active\s*\{[\s\S]*background:\s*transparent;/);
  assert.match(css, /\.craft-assist-editor-role-group\.active\s+\.craft-assist-role-tag\s*\{[\s\S]*border-color:/);
  assert.match(css, /body\.theme-inkblue \.craft-assist-editor-modal \.craft-assist-editor-role-group\.active\s*\{[\s\S]*border-color:/);
