  assert.match(html, /id="craftAddPresetBtn"[^>]*title="添加配方"[^>]*aria-label="添加配方"/);
  assert.doesNotMatch(html, /id="craftAssistApplyBtn"/);
  assert.match(html, /id="craftAssistEditorModal"/);
