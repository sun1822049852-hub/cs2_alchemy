  assert.match(html, /id="craftAssistEditorPrediction"/);
  assert.match(html, /id="craftAssistMainRoleGroup"[^>]*data-role="main"/);
  assert.match(html, /id="craftAssistAuxRoleGroup"[^>]*data-role="aux"/);
  assert.doesNotMatch(html, /id="craftAssist(?:Main|Aux)RoleBtn"|craft-assist-editor-role-tabs/);
  assert.match(html, /data-rarity-tag="1"[^>]*>消费级</);
  assert.match(html, /data-rarity-tag="2"[^>]*>工业级</);
  assert.match(html, /data-rarity-tag="3"[^>]*>军规级</);
  assert.match(html, /id="craftAssistWarehouseSourceBtn"/);
  assert.match(html, /id="craftAssistOutcomeModal"[^>]*role="dialog"/);
  assert.match(html, /id="craftAssistOutcomeModalRarityBadge"/);
  assert.doesNotMatch(html, /craftAssistOutcomeModalStatusBadge|可精修/);
  assert.match(html, /id="craftAssistOutcomeModalWearLabel"/);
