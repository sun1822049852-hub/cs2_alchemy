const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const html = fs.readFileSync(path.resolve(__dirname, "../ui/index.html"), "utf8");
const css = fs.readFileSync(path.resolve(__dirname, "../ui/styles.css"), "utf8");
const app = fs.readFileSync(path.resolve(__dirname, "../ui/app.js"), "utf8");
const craftService = fs.readFileSync(path.resolve(__dirname, "../src/services/craftService.js"), "utf8");
